import { NextResponse } from 'next/server';

export const maxDuration = 60;

export async function POST(request: Request) {
  try {
    const { date, tithi, nakshatra, angle, language } = await request.json();
    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      return NextResponse.json({ error: "Missing API Key" }, { status: 500 });
    }

    // STEP 1: AI Scriptwriter (Gemini 3.8 Flash)
    const scriptPrompt = `You are a cinematic Vedic astronomer. Today is ${date}. Current Tithi: ${tithi}. Active Nakshatra: ${nakshatra}. The Moon is ${angle} degrees ahead of the Sun. Language: ${language === 'hi' ? 'Hindi' : 'English'}.

CRITICAL: Write maximum 15 to 20 words. Be extremely concise. State the Moon's position, the Tithi, the Nakshatra, and the Navratri festival deity. Do not add poetic filler.

CRITICAL INSTRUCTION: Output ONLY the raw spoken text. Do not include introductory filler, quotes, or markdown.`;

    const textRes = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ role: 'user', parts: [{ text: scriptPrompt }] }]
        })
      }
    );

    if (!textRes.ok) throw new Error("Failed to generate dynamic script");
    
    const textData = await textRes.json();
    const generatedScript = textData.candidates?.[0]?.content?.parts?.[0]?.text?.trim();

    if (!generatedScript) throw new Error("No script generated by AI");

    // STEP 2: AI Voice Synthesizer (Gemini 3.8 Flash TTS)
    const audioRes = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash-tts:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          // Notice we pass ONLY the clean generated script here
          contents: [{ role: 'user', parts: [{ text: generatedScript }] }],
          generationConfig: {
            responseModalities: ["AUDIO"],
            speechConfig: {
              voiceConfig: {
                prebuiltVoiceConfig: {
                  voiceName: language === 'hi' ? "Aoede" : "Puck" 
                }
              }
            }
          }
        })
      }
    );

    if (!audioRes.ok) {
      const errText = await audioRes.text();
      console.error('Google TTS Error:', errText);
      throw new Error('Failed to generate audio buffer');
    }

    const audioData = await audioRes.json();
    const audioPart = audioData.candidates?.[0]?.content?.parts?.find(
      (part: any) => part.inlineData?.mimeType?.startsWith('audio/')
    );

    if (!audioPart) throw new Error("No audio data returned from TTS model");

    // Send both the clean text (for subtitles) and the audio buffer back to the client
    return NextResponse.json({ 
      generatedText: generatedScript,
      audioBase64: audioPart.inlineData.data 
    });

  } catch (error: any) {
    console.error("API Route Error:", error);
    return NextResponse.json({ error: error.message || "Internal Server Error" }, { status: 500 });
  }
}